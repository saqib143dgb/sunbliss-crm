-- Contact activity only: not verified email history, not a payment ledger.
CREATE TABLE IF NOT EXISTS public.crm_collection_contacts (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 unit_id bigint NOT NULL REFERENCES public.units(id),
 source_task_id bigint REFERENCES public.scheduled_actions(id) ON DELETE SET NULL,
 actor_id uuid NOT NULL REFERENCES public.profiles(id),
 contact_method text NOT NULL CHECK (contact_method IN ('email','call','whatsapp')),
 outcome text NOT NULL CHECK (outcome IN ('no_response','promise','partial_payment_commitment','payment_issue','extension_request')),
 schedule_ids bigint[] NOT NULL,
 followup_date date,
 note text,
 created_at timestamptz NOT NULL DEFAULT now(),
 CHECK (cardinality(schedule_ids) BETWEEN 1 AND 20)
);
CREATE INDEX IF NOT EXISTS crm_collection_contacts_task_idx ON public.crm_collection_contacts(source_task_id,created_at DESC);
CREATE TABLE IF NOT EXISTS public.crm_collection_promises (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 contact_id bigint NOT NULL REFERENCES public.crm_collection_contacts(id) ON DELETE CASCADE,
 unit_id bigint NOT NULL REFERENCES public.units(id),
 payment_schedule_id bigint NOT NULL REFERENCES public.payment_schedule(id),
 promised_amount numeric(14,2) NOT NULL CHECK (promised_amount>0),
 promised_date date NOT NULL,
 reminder_task_id bigint REFERENCES public.scheduled_actions(id) ON DELETE SET NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(contact_id,payment_schedule_id,promised_date)
);
CREATE INDEX IF NOT EXISTS crm_collection_promises_schedule_idx ON public.crm_collection_promises(payment_schedule_id,promised_date);
ALTER TABLE public.crm_collection_contacts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.crm_collection_promises ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.crm_collection_contacts,public.crm_collection_promises FROM public,anon,authenticated;
GRANT SELECT ON public.crm_collection_contacts,public.crm_collection_promises TO authenticated;
CREATE POLICY crm_collection_contacts_read ON public.crm_collection_contacts FOR SELECT TO authenticated
 USING (EXISTS(SELECT 1 FROM public.profiles p WHERE p.id=auth.uid() AND p.role::text IN ('crm_officer','manager')));
CREATE POLICY crm_collection_promises_read ON public.crm_collection_promises FOR SELECT TO authenticated
 USING (EXISTS(SELECT 1 FROM public.profiles p WHERE p.id=auth.uid() AND p.role::text IN ('crm_officer','manager')));

CREATE OR REPLACE FUNCTION public.crm_record_grouped_collection_contact(
 p_task_id bigint, p_expected_updated_at timestamptz, p_outcome text,
 p_schedule_ids bigint[], p_method text, p_note text DEFAULT NULL,
 p_next_date date DEFAULT NULL, p_allocations jsonb DEFAULT '[]'::jsonb
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO public AS $body$
DECLARE
 t public.scheduled_actions%rowtype;
 v_existing_ids bigint[]; v_ids bigint[]; v_id bigint;
 v_today date:=(now() AT TIME ZONE 'Asia/Dubai')::date;
 v_event bigint; v_line jsonb; v_amt numeric; v_dt date;
 v_stage public.payment_schedule%rowtype; v_outstanding numeric;
 v_group record; v_group_key text; v_new_task bigint; v_n integer:=0;
 v_task_count integer:=0; v_total numeric:=0; v_note text;
 v_extension_result jsonb; v_extension_count integer:=0;
BEGIN
 IF NOT EXISTS(SELECT 1 FROM public.profiles WHERE id=auth.uid() AND role::text='crm_officer') THEN
  RAISE EXCEPTION 'Only CRM officers can update customer follow-ups.';
 END IF;
 IF p_method NOT IN ('email','call','whatsapp') OR p_method IS NULL THEN
  RAISE EXCEPTION 'Select Email, Call or WhatsApp.';
 END IF;
 IF p_outcome NOT IN ('no_response','promise','partial_payment_commitment','payment_issue','extension_request') OR p_outcome IS NULL THEN
  RAISE EXCEPTION 'Choose a supported customer response.';
 END IF;
 IF p_outcome IN ('no_response','payment_issue','extension_request') AND (p_next_date IS NULL OR p_next_date<v_today) THEN
  RAISE EXCEPTION 'Select today or a future follow-up / requested extension date.';
 END IF;
 IF p_outcome IN ('payment_issue','extension_request') AND nullif(btrim(p_note),'') IS NULL THEN
  RAISE EXCEPTION 'Enter the customer reason or request details.';
 END IF;
 IF p_schedule_ids IS NULL OR cardinality(p_schedule_ids) NOT BETWEEN 1 AND 20 THEN
  RAISE EXCEPTION 'Select at least one related payment.';
 END IF;
 SELECT * INTO t FROM public.scheduled_actions WHERE id=p_task_id FOR UPDATE;
 IF NOT FOUND OR t.status<>'pending' OR t.updated_at IS DISTINCT FROM p_expected_updated_at THEN
  RAISE EXCEPTION 'This task has changed. Refresh and reopen it.';
 END IF;
 IF t.transaction_id IS NOT NULL OR t.commitment_part_id IS NOT NULL OR t.extension_request_id IS NOT NULL OR
    t.workflow_kind IN ('accounts_confirmation','cheque_clearance','payment_receipt','spa','extension_approval','extension_customer_confirmation','extension_clarification','modification_request') OR
    t.auto_kind NOT IN ('overdue_follow_up','extension_residual_overdue','extension_uncovered_overdue') AND t.auto_kind IS NOT NULL THEN
  RAISE EXCEPTION 'Use the dedicated workflow for this task.';
 END IF;
 IF strpos(coalesce(t.auto_key,''),'|schedules:')>0 THEN
  v_existing_ids:=string_to_array(split_part(split_part(t.auto_key,'|schedules:',2),'|',1),',')::bigint[];
 ELSIF strpos(coalesce(t.auto_key,''),'|schedule:')>0 THEN
  v_existing_ids:=ARRAY[split_part(split_part(t.auto_key,'|schedule:',2),'|',1)::bigint];
 ELSIF t.schedule_id IS NOT NULL THEN
  v_existing_ids:=ARRAY[t.schedule_id];
 ELSE
  RAISE EXCEPTION 'This task has no linked payments. Edit it to link the payment first.';
 END IF;
 SELECT array_agg(DISTINCT x ORDER BY x) INTO v_ids FROM unnest(p_schedule_ids) AS x;
 IF cardinality(v_ids) IS DISTINCT FROM cardinality(p_schedule_ids) OR
    EXISTS(SELECT 1 FROM unnest(v_ids) id WHERE id IS NULL OR id<=0 OR NOT id=ANY(v_existing_ids)) THEN
  RAISE EXCEPTION 'Select only the installments already linked to this task, without duplicates.';
 END IF;
 IF (SELECT count(*) FROM public.payment_schedule WHERE unit_id=t.unit_id AND id=ANY(v_ids))<>cardinality(v_ids) THEN
  RAISE EXCEPTION 'One of the selected installments does not belong to this unit.';
 END IF;
 PERFORM set_config('crm.task_outcome',p_outcome,true);
 IF p_outcome IN ('promise','partial_payment_commitment') AND
    (p_allocations IS NULL OR jsonb_typeof(p_allocations)<>'array' OR jsonb_array_length(p_allocations) NOT BETWEEN 1 AND 30) THEN
  RAISE EXCEPTION 'Enter at least one amount and promise date.';
 END IF;
 IF p_outcome NOT IN ('promise','partial_payment_commitment') AND p_allocations<>'[]'::jsonb THEN
  RAISE EXCEPTION 'Payment promises are only accepted for promise outcomes.';
 END IF;

 INSERT INTO public.crm_collection_contacts(unit_id,source_task_id,actor_id,contact_method,outcome,schedule_ids,followup_date,note)
 VALUES(t.unit_id,t.id,auth.uid(),p_method,p_outcome,v_ids,p_next_date,nullif(btrim(p_note),''))
 RETURNING id INTO v_event;
 IF p_outcome IN ('promise','partial_payment_commitment') THEN
  FOR v_line IN SELECT value FROM jsonb_array_elements(p_allocations) LOOP
   BEGIN
    v_id:=(v_line->>'schedule_id')::bigint;
    v_amt:=round((v_line->>'amount')::numeric,2);
    v_dt:=(v_line->>'date')::date;
   EXCEPTION WHEN others THEN
    RAISE EXCEPTION 'Enter a valid installment, amount and date for each promised payment.';
   END;
   IF NOT v_id=ANY(v_ids) OR v_id IS NULL OR v_amt IS NULL OR v_amt<=0 OR v_dt IS NULL OR v_dt<v_today THEN
    RAISE EXCEPTION 'Check the selected installment, promised amount and date.';
   END IF;
   SELECT * INTO v_stage FROM public.payment_schedule WHERE id=v_id AND unit_id=t.unit_id FOR UPDATE;
   SELECT greatest(0,coalesce(cv.revised_due_amount,cv.due_amount,0)-coalesce(cv.paid_amount,0)-
      coalesce((SELECT sum(c.amount) FROM public.credit_notes c WHERE c.payment_schedule_id=v_id),0))
    INTO v_outstanding FROM public.current_payment_schedule cv WHERE cv.id=v_id;
   IF coalesce(v_outstanding,0)<=0.01 THEN RAISE EXCEPTION 'Selected installment is already settled.'; END IF;
   IF EXISTS(SELECT 1 FROM public.crm_collection_promises WHERE contact_id=v_event AND payment_schedule_id=v_id AND promised_date=v_dt) THEN
    RAISE EXCEPTION 'Combine amounts for the same installment and promise date.';
   END IF;
   INSERT INTO public.crm_collection_promises(contact_id,unit_id,payment_schedule_id,promised_amount,promised_date)
     VALUES(v_event,t.unit_id,v_id,v_amt,v_dt);
   v_total:=v_total+v_amt;
  END LOOP;
  FOR v_id IN SELECT unnest(v_ids) LOOP
   IF NOT EXISTS(SELECT 1 FROM public.crm_collection_promises WHERE contact_id=v_event AND payment_schedule_id=v_id) THEN
    RAISE EXCEPTION 'Provide an amount and promise date for each selected installment.';
   END IF;
   SELECT greatest(0,coalesce(cv.revised_due_amount,cv.due_amount,0)-coalesce(cv.paid_amount,0)-
      coalesce((SELECT sum(c.amount) FROM public.credit_notes c WHERE c.payment_schedule_id=v_id),0))
    INTO v_outstanding FROM public.current_payment_schedule cv WHERE cv.id=v_id;
   IF (SELECT sum(promised_amount) FROM public.crm_collection_promises WHERE contact_id=v_event AND payment_schedule_id=v_id)>v_outstanding+0.01 THEN
    RAISE EXCEPTION 'Promised amount exceeds the outstanding balance of payment schedule %.',v_id;
   END IF;
  END LOOP;
  -- One reminder per promised DATE. Preserve separate allocations under each reminder.
  FOR v_group IN
   SELECT promised_date AS d,array_agg(DISTINCT payment_schedule_id ORDER BY payment_schedule_id) AS ids,
          sum(promised_amount) AS total
   FROM public.crm_collection_promises WHERE contact_id=v_event GROUP BY promised_date ORDER BY promised_date
  LOOP
   v_task_count:=v_task_count+1;
   v_group_key:='manual_payment|unit:'||t.unit_id||
     CASE WHEN cardinality(v_group.ids)=1 THEN '|schedule:'||v_group.ids[1]
          ELSE '|schedules:'||array_to_string(v_group.ids,',') END;
   v_note:='Customer promised AED '||to_char(v_group.total,'FM999G999G999G990D00')||
        ' by '||to_char(v_group.d,'DD Mon YYYY')||'. '||
        (SELECT string_agg(ps.stage_name||' AED '||to_char(cp.promised_amount,'FM999G999G999G990D00'),'; ' ORDER BY ps.id)
          FROM public.crm_collection_promises cp JOIN public.payment_schedule ps ON ps.id=cp.payment_schedule_id
          WHERE cp.contact_id=v_event AND cp.promised_date=v_group.d)||
        '. Contact: '||p_method||CASE WHEN nullif(btrim(p_note),'') IS NULL THEN '' ELSE '. '||btrim(p_note) END;
   IF v_task_count=1 THEN
    IF EXISTS(SELECT 1 FROM public.scheduled_actions z WHERE z.unit_id=t.unit_id AND z.id<>t.id AND z.status='pending'
      AND z.source='manual' AND z.auto_kind IS NULL AND z.due_date=v_group.d
      AND (z.auto_key=v_group_key OR
           z.schedule_id=ANY(v_group.ids)) AND z.transaction_id IS NULL AND z.extension_request_id IS NULL) THEN
      RAISE EXCEPTION 'An active follow-up already covers these payments on the promised date. Review it first.';
    END IF;
    UPDATE public.scheduled_actions SET action_label=CASE WHEN p_outcome='partial_payment_commitment' THEN 'Follow up for Partial Payment' ELSE 'Follow up on Promised Payment' END,
      due_date=v_group.d,priority='Medium',note=v_note,source='manual',auto_kind=NULL,
      workflow_kind='promise_follow_up',auto_key=v_group_key,
      schedule_id=NULL, -- group key is canonical; multiple promise dates must not collide with the pending manual-schedule uniqueness rule
      updated_at=now() WHERE id=t.id;
    v_new_task:=t.id;
   ELSE
    IF EXISTS(SELECT 1 FROM public.scheduled_actions z WHERE z.unit_id=t.unit_id AND z.status='pending'
      AND z.due_date=v_group.d AND z.auto_key=v_group_key AND z.source='manual' AND z.auto_kind IS NULL) THEN
      RAISE EXCEPTION 'An active follow-up already exists for this promised date and installment group.';
    END IF;
    INSERT INTO public.scheduled_actions(unit_id,action_label,due_date,priority,note,status,owner_id,source,auto_kind,auto_key,schedule_id,workflow_kind,created_at,updated_at)
    VALUES(t.unit_id,CASE WHEN p_outcome='partial_payment_commitment' THEN 'Follow up for Partial Payment' ELSE 'Follow up on Promised Payment' END,
      v_group.d,'Medium',v_note,'pending',coalesce(t.owner_id,auth.uid()),'manual',NULL,v_group_key,
      NULL,'promise_follow_up',now(),now())
    RETURNING id INTO v_new_task;
   END IF;
   UPDATE public.crm_collection_promises SET reminder_task_id=v_new_task WHERE contact_id=v_event AND promised_date=v_group.d;
  END LOOP;
 ELSIF p_outcome='extension_request' THEN
  -- Separate management approval for each installment; no contractual due-date mutation.
  FOR v_id IN SELECT unnest(v_ids) LOOP
   v_extension_result:=public.crm_create_payment_extension_request(t.unit_id,v_id,p_next_date,p_note);
   v_extension_count:=v_extension_count+1;
  END LOOP;
 ELSE
  v_group_key:='manual_payment|unit:'||t.unit_id||
    CASE WHEN cardinality(v_existing_ids)=1 THEN '|schedule:'||v_existing_ids[1]
         ELSE '|schedules:'||(SELECT string_agg(id::text,',' ORDER BY id) FROM unnest(v_existing_ids) id) END;
  IF EXISTS(SELECT 1 FROM public.scheduled_actions z WHERE z.id<>t.id AND z.unit_id=t.unit_id
    AND z.status='pending' AND z.source='manual' AND z.auto_kind IS NULL AND z.auto_key=v_group_key
    AND z.due_date=p_next_date AND z.workflow_kind IN ('payment_follow_up','payment_query')) THEN
   RAISE EXCEPTION 'These payments already have a follow-up on this date.';
  END IF;
  UPDATE public.scheduled_actions SET
    action_label=CASE WHEN p_outcome='payment_issue' THEN 'Resolve Payment Query' ELSE 'Payment Follow-up with Customer' END,
    due_date=p_next_date,note=initcap(replace(p_method,'_',' '))||' contact: '||
      CASE WHEN p_outcome='no_response' THEN 'No response' ELSE 'Payment query' END||
      CASE WHEN nullif(btrim(p_note),'') IS NULL THEN '' ELSE '. '||btrim(p_note) END,
    source='manual',auto_kind=NULL,auto_key=v_group_key,
    schedule_id=CASE WHEN cardinality(v_existing_ids)=1 THEN v_existing_ids[1] ELSE NULL END,
    workflow_kind=CASE WHEN p_outcome='payment_issue' THEN 'payment_query' ELSE 'payment_follow_up' END,
    updated_at=now() WHERE id=t.id;
 END IF;
 RETURN jsonb_build_object('contact_id',v_event,'task_id',t.id,'outcome',p_outcome,
     'selected_payments',v_ids,'reminders',v_task_count,'promised_amount',v_total,'management_requests',v_extension_count);
END
$body$;
REVOKE ALL ON FUNCTION public.crm_record_grouped_collection_contact(bigint,timestamptz,text,bigint[],text,text,date,jsonb) FROM public,anon;
GRANT EXECUTE ON FUNCTION public.crm_record_grouped_collection_contact(bigint,timestamptz,text,bigint[],text,text,date,jsonb) TO authenticated;
